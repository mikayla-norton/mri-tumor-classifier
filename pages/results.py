"""Results - model performance, read from generated report artifacts.

Phase 6: this page must not contain training/evaluation logic itself
(the original version imported TensorFlow, EfficientNet, sklearn's
train_test_split, etc. directly into a Streamlit page). Everything shown
here is read from files produced by `training/evaluate.py`.
"""

import json

import pandas as pd
import streamlit as st

from src import config

st.set_page_config(page_title="Results - NeuroNet MRI", page_icon="📊", layout="wide")
st.title("Results")

st.markdown(
    "All numbers on this page are read from `reports/`, generated by "
    "`training/evaluate.py` running against `mri-data/Testing/` - a test "
    "set the model never sees during training or validation."
)

# --------------------------------------------------------------------------
# Dataset summary (only shown if the dataset happens to be present
# locally - it's intentionally excluded from the deployed app/repo, see
# .gitignore, so this section is optional rather than assumed).
# --------------------------------------------------------------------------

if config.DATA_DIR.exists():
    st.header("Dataset summary")
    rows = []
    for split_name, split_dir in [("Training", config.TRAIN_DATA_DIR), ("Testing", config.TEST_DATA_DIR)]:
        if not split_dir.exists():
            continue
        for folder_name, class_name in config.DATASET_FOLDER_TO_CLASS.items():
            folder = split_dir / folder_name
            if folder.exists():
                count = sum(1 for p in folder.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png"))
                rows.append({"Split": split_name, "Class": config.CLASS_DISPLAY_NAMES[class_name], "Images": count})
    if rows:
        counts_df = pd.DataFrame(rows).pivot(index="Class", columns="Split", values="Images")
        st.dataframe(counts_df, use_container_width=True)
        st.caption(
            "Class counts are imbalanced (notably fewer `no_tumor` images "
            "than tumor classes) - see Methodology for how this is handled."
        )

# --------------------------------------------------------------------------
# Current (corrected-pipeline) results
# --------------------------------------------------------------------------

st.header("Current model")

if not config.METRICS_JSON_PATH.exists():
    st.info(
        "No current evaluation report found yet. This project ships "
        "without a retrained model in this environment - run "
        "`python training/train.py` followed by `python training/evaluate.py` "
        "to produce `reports/metrics.json` and populate this section. "
        "In the meantime, see **Legacy baseline** below for the model "
        "artifact and numbers shipped in the original project, which used "
        "a flawed evaluation methodology and should not be treated as a "
        "true measure of held-out performance.",
        icon="ℹ️",
    )
else:
    with open(config.METRICS_JSON_PATH) as f:
        metrics = json.load(f)

    col1, col2, col3 = st.columns(3)
    col1.metric("Accuracy", f"{metrics['accuracy']:.1%}")
    col2.metric("Macro F1", f"{metrics['macro_f1']:.1%}")
    col3.metric("Test samples", metrics["n_samples"])
    st.caption(f"Evaluated on: {metrics['dataset_split']}")

    st.subheader("Per-class performance")
    per_class_df = pd.DataFrame(metrics["per_class"]).transpose()
    per_class_df.index = [config.CLASS_DISPLAY_NAMES[i] for i in per_class_df.index]
    st.dataframe(per_class_df, use_container_width=True)
    st.caption(
        "Recall matters most here: a low recall on a tumor class means "
        "the model is more likely to miss that tumor type entirely, which "
        "is a more serious failure mode than confusing two tumor subtypes."
    )

    if config.CONFUSION_MATRIX_PATH.exists():
        st.subheader("Confusion matrix")
        cm_df = pd.read_csv(config.CONFUSION_MATRIX_PATH, index_col=0)
        st.dataframe(cm_df, use_container_width=True)
        st.caption("Rows = true label, columns = predicted label.")

    if config.TRAINING_HISTORY_PATH.exists():
        st.subheader("Training history")
        history_df = pd.read_csv(config.TRAINING_HISTORY_PATH)
        accuracy_cols = [c for c in ["accuracy", "val_accuracy"] if c in history_df.columns]
        loss_cols = [c for c in ["loss", "val_loss"] if c in history_df.columns]
        if accuracy_cols:
            st.line_chart(history_df.set_index("epoch")[accuracy_cols])
        if loss_cols:
            st.line_chart(history_df.set_index("epoch")[loss_cols])

    if metrics.get("training_config"):
        with st.expander("Training configuration used for this run"):
            st.json(metrics["training_config"])

    with st.expander("Model architecture summary"):
        try:
            from src.model import get_cached_model

            model = get_cached_model()
            lines: list[str] = []
            model.summary(print_fn=lambda line: lines.append(line))
            st.text("\n".join(lines))
        except Exception as exc:  # model missing, TF not installed, etc.
            st.caption(f"Model summary unavailable ({exc}).")

# --------------------------------------------------------------------------
# Legacy baseline, clearly separated and labeled
# --------------------------------------------------------------------------

st.header("Legacy baseline (for reference only)")
st.warning(
    "**These numbers come from the original project and used a flawed "
    "evaluation methodology**: the original `Training/` and `Testing/` "
    "folders were combined and re-split, so the reported \"test\" set was "
    "not a true held-out set. They are shown here only for historical "
    "reference and provenance, not as a trustworthy measure of the "
    "model's real performance. See `reports/baseline_legacy/README.md`.",
    icon="🚧",
)

try:
    legacy_report = pd.read_csv(
        config.PROJECT_ROOT / "reports" / "baseline_legacy" / "classification_report.csv",
        index_col=0,
    )
    with st.expander("Show legacy (flawed-split) classification report"):
        st.dataframe(legacy_report, use_container_width=True)
except FileNotFoundError:
    pass
